using System.Collections.Generic;
using System.Linq;
using System.Text;
using Microsoft.CodeAnalysis.CSharp;

namespace Voxear.Analyzers;

/// <summary>Writes the generated Actions: a class for each map, an InputActionRef for each of its actions.</summary>
internal static class InputActionsSource
{
	public static string Write(IEnumerable<InputActionEntry> actions, string rootNamespace)
	{
		var source = new StringBuilder("// <auto-generated/>\n#nullable enable\n\n");
		if (rootNamespace.Length > 0)
		{
			source.Append($"namespace {rootNamespace};\n\n");
		}
		source.Append("/// <summary>The project's input actions, by map, as InputActionRefs: Actions.Player.Jump.</summary>\n");
		source.Append("internal static class Actions\n{\n");
		var maps = actions.GroupBy(action => action.Map).ToList();
		var mapNames = new HashSet<string> { "Actions" };
		for (var at = 0; at < maps.Count; at++)
		{
			source.Append(at > 0 ? "\n" : string.Empty);
			var mapName = Unique(Identifier(maps[at].Key), mapNames);
			source.Append($"\t/// <summary>The {Escape(maps[at].Key)} map's actions.</summary>\n");
			source.Append($"\tpublic static class {mapName}\n\t{{\n");
			var names = new HashSet<string> { mapName };
			foreach (var action in maps[at])
			{
				var name = Unique(Identifier(action.Name), names);
				var id = SymbolDisplay.FormatLiteral(action.Id, quote: true);
				source.Append($"\t\t/// <summary>{Escape(action.Map)}/{Escape(action.Name)}</summary>\n");
				source.Append($"\t\tpublic static global::Voxear.InputActionRef {name} => new global::Voxear.InputActionRef({id});\n");
			}
			source.Append("\t}\n");
		}
		source.Append("}\n");
		return source.ToString();
	}

	/// <summary>A name as C# can write it: its words run together, each starting with a capital.</summary>
	private static string Identifier(string name)
	{
		var words = new List<string> { string.Empty };
		foreach (var c in name)
		{
			if (char.IsLetterOrDigit(c) || c == '_')
			{
				words[words.Count - 1] += c;
			}
			else
			{
				words.Add(string.Empty);
			}
		}
		var joined = string.Concat(words.Where(word => word.Length > 0).Select(word => char.ToUpperInvariant(word[0]) + word.Substring(1)));
		if (joined.Length == 0 || char.IsDigit(joined[0]))
		{
			joined = "_" + joined;
		}
		return SyntaxFacts.GetKeywordKind(joined) == SyntaxKind.None ? joined : "@" + joined;
	}

	/// <summary>The name, or the name and a number when one already has it.</summary>
	private static string Unique(string name, HashSet<string> taken)
	{
		var unique = name;
		for (var number = 2; !taken.Add(unique); number++)
		{
			unique = $"{name}{number}";
		}
		return unique;
	}

	private static string Escape(string text)
	{
		return text.Replace("&", "&amp;").Replace("<", "&lt;").Replace(">", "&gt;");
	}
}
