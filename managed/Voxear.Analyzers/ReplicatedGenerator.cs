using System.Collections.Generic;
using System.Collections.Immutable;
using System.Linq;
using System.Text;
using Microsoft.CodeAnalysis;
using Microsoft.CodeAnalysis.CSharp;
using Microsoft.CodeAnalysis.CSharp.Syntax;

namespace Voxear.Analyzers;

/// <summary>
/// Writes [Replicated] partial properties: each keeps its value in a field of its own and, set to something new,
/// tells Replication, so a change is noticed when it is made rather than looked for every tick. The behaviour gets
/// IReplicated too, writing and reading every replicated value in the order the properties are declared.
/// </summary>
[Generator(LanguageNames.CSharp)]
public sealed class ReplicatedGenerator : IIncrementalGenerator
{
	private const string Attribute = "Voxear.ReplicatedAttribute";

	public void Initialize(IncrementalGeneratorInitializationContext context)
	{
		var properties = context.SyntaxProvider.ForAttributeWithMetadataName(
			Attribute,
			static (node, _) => node is PropertyDeclarationSyntax,
			static (found, _) => Read(found));
		context.RegisterSourceOutput(properties.Collect(), Generate);
	}

	private static ReplicatedProperty? Read(GeneratorAttributeSyntaxContext found)
	{
		if (found.TargetSymbol is not IPropertySymbol property || found.TargetNode is not PropertyDeclarationSyntax syntax)
		{
			return null;
		}
		var partial = syntax.Modifiers.Any(m => m.IsKind(SyntaxKind.PartialKeyword));
		var type = property.ContainingType;
		var space = type.ContainingNamespace.IsGlobalNamespace ? string.Empty : type.ContainingNamespace.ToDisplayString();
		var kind = NetTypes.Kind(property, property.Type);
		return new ReplicatedProperty(
			space,
			type.Name,
			type.ToDisplayString(),
			property.Name,
			property.Type.ToDisplayString(SymbolDisplayFormat.FullyQualifiedFormat),
			NetTypes.Accessibility(property.DeclaredAccessibility),
			kind,
			partial && type.ContainingType == null && type.TypeParameters.IsEmpty,
			syntax.GetLocation());
	}

	private static void Generate(SourceProductionContext context, ImmutableArray<ReplicatedProperty?> found)
	{
		var properties = found.Where(p => p != null).Select(p => p!).ToList();
		foreach (var wrong in properties.Where(p => !p.Partial))
		{
			context.ReportDiagnostic(Diagnostic.Create(Diagnostics.NotPartial, wrong.Location, wrong.Name, wrong.TypeName));
		}
		foreach (var wrong in properties.Where(p => p.Partial && p.Kind == null))
		{
			context.ReportDiagnostic(Diagnostic.Create(Diagnostics.NotReplicable, wrong.Location, wrong.Name, wrong.Type));
		}
		var usable = properties.Where(p => p.Partial && p.Kind != null);
		foreach (var type in usable.GroupBy(p => p.FullTypeName))
		{
			var list = type.ToList();
			context.AddSource($"{type.Key}.Replicated.g.cs", Source(list));
		}
	}

	private static string Source(List<ReplicatedProperty> properties)
	{
		var first = properties[0];
		var text = new StringBuilder();
		text.AppendLine("// <auto-generated/>");
		text.AppendLine("#nullable enable");
		if (first.Namespace.Length > 0)
		{
			text.AppendLine($"namespace {first.Namespace};");
		}
		text.AppendLine();
		text.AppendLine($"partial class {first.TypeName} : global::Voxear.IReplicated");
		text.AppendLine("{");
		foreach (var property in properties)
		{
			var field = Field(property);
			// A world position's value moves with the world's middle, as fields so marked do.
			if (property.Kind == NetTypes.WorldPosition)
			{
				text.AppendLine("\t[global::Voxear.WorldPosition]");
			}
			text.AppendLine($"\tprivate {property.Type} {field};");
			text.AppendLine();
			text.AppendLine($"\t{property.Access} partial {property.Type} {property.Name}");
			text.AppendLine("\t{");
			text.AppendLine($"\t\tget {{ return {field}; }}");
			text.AppendLine("\t\tset");
			text.AppendLine("\t\t{");
			text.AppendLine($"\t\t\tif (global::System.Collections.Generic.EqualityComparer<{property.Type}>.Default.Equals({field}, value))");
			text.AppendLine("\t\t\t{");
			text.AppendLine("\t\t\t\treturn;");
			text.AppendLine("\t\t\t}");
			text.AppendLine($"\t\t\t{field} = value;");
			text.AppendLine("\t\t\tglobal::Voxear.Replication.Changed(this);");
			text.AppendLine("\t\t}");
			text.AppendLine("\t}");
			text.AppendLine();
		}
		text.AppendLine("\tvoid global::Voxear.IReplicated.WriteReplicated(global::Voxear.NetWriter writer)");
		text.AppendLine("\t{");
		foreach (var property in properties)
		{
			text.AppendLine($"\t\twriter.Write({NetTypes.Written(property.Kind!, Field(property))});");
		}
		text.AppendLine("\t}");
		text.AppendLine();
		text.AppendLine("\tvoid global::Voxear.IReplicated.ReadReplicated(global::Voxear.NetReader reader)");
		text.AppendLine("\t{");
		foreach (var property in properties)
		{
			text.AppendLine($"\t\t{Field(property)} = {NetTypes.Read(property.Kind!, property.Type)};");
		}
		text.AppendLine("\t}");
		text.AppendLine("}");
		return text.ToString();
	}

	private static string Field(ReplicatedProperty property)
	{
		return "replicated" + property.Name;
	}
}
