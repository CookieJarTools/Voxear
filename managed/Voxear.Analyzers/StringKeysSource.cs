using System.Collections.Generic;
using System.Linq;
using System.Text;
using Microsoft.CodeAnalysis.CSharp;

namespace Voxear.Analyzers;

/// <summary>Writes the generated Strings: a class for each group of keys, a LocalizedString for each key in it.</summary>
internal static class StringKeysSource
{
	/// <summary>What every class has from object, which a key of the same name hides.</summary>
	private static readonly HashSet<string> ObjectMembers = ["Equals", "GetHashCode", "GetType", "ToString", "ReferenceEquals", "MemberwiseClone"];

	/// <summary>The file, in rootNamespace, or the global namespace when that is empty.</summary>
	public static string Write(StringKeyNode root, string rootNamespace)
	{
		var source = new StringBuilder("// <auto-generated/>\n#nullable enable\n\n");
		if (rootNamespace.Length > 0)
		{
			source.Append($"namespace {rootNamespace};\n\n");
		}
		source.Append("/// <summary>The keys of the project's string tables, as LocalizedStrings.</summary>\n");
		source.Append($"internal static class {root.Name}\n{{\n");
		WriteMembers(source, root, "\t");
		source.Append("}\n");
		return source.ToString();
	}

	/// <summary>A group's keys, then the groups inside it, each in order of name.</summary>
	private static void WriteMembers(StringBuilder source, StringKeyNode group, string indent)
	{
		var keys = group.Children.Values.Where(child => !child.IsGroup).ToList();
		var groups = group.Children.Values.Where(child => child.IsGroup).ToList();
		for (var at = 0; at < keys.Count; at++)
		{
			source.Append(at > 0 ? "\n" : string.Empty);
			WriteKey(source, keys[at], indent);
		}
		foreach (var inner in groups)
		{
			source.Append(keys.Count > 0 || inner != groups[0] ? "\n" : string.Empty);
			source.Append($"{indent}public static class {inner.Name}\n{indent}{{\n");
			WriteMembers(source, inner, indent + "\t");
			source.Append($"{indent}}}\n");
		}
	}

	private static void WriteKey(StringBuilder source, StringKeyNode node, string indent)
	{
		var entry = node.Keys[0];
		WriteSummary(source, entry, indent);
		var hides = ObjectMembers.Contains(node.Name) ? "new " : string.Empty;
		var key = SymbolDisplay.FormatLiteral(entry.Key, quote: true);
		source.Append($"{indent}public static {hides}global::Voxear.LocalizedString {node.Name} => new global::Voxear.LocalizedString({key});\n");
	}

	/// <summary>The key's text in the table's first language, then what it says for translators.</summary>
	private static void WriteSummary(StringBuilder source, StringTableEntry entry, string indent)
	{
		var parts = new List<string>();
		if (entry.Text.Length > 0)
		{
			parts.Add(Escape(entry.Text));
		}
		if (entry.Comment.Length > 0)
		{
			parts.Add($"<para>{Escape(entry.Comment)}</para>");
		}
		if (parts.Count == 0)
		{
			return;
		}
		source.Append($"{indent}/// <summary>\n");
		foreach (var line in string.Join("\n", parts).Split('\n'))
		{
			source.Append($"{indent}/// {line.TrimEnd('\r')}\n");
		}
		source.Append($"{indent}/// </summary>\n");
	}

	/// <summary>Text as a doc comment holds it: XML's special characters escaped, and control characters, which XML cannot hold, left out.</summary>
	private static string Escape(string text)
	{
		var kept = new string(text.Where(c => c == '\n' || c == '\t' || !char.IsControl(c)).ToArray());
		return kept.Replace("&", "&amp;").Replace("<", "&lt;").Replace(">", "&gt;");
	}
}
