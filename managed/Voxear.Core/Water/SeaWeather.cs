namespace Voxear;

/// <summary>What the weather makes of an Ocean's sea.</summary>
public enum SeaWeather
{
	/// <summary>A long, low swell under a light breeze.</summary>
	Calm,

	/// <summary>A steady swell and a fresh breeze, with some whitecaps.</summary>
	Normal,

	/// <summary>A heavy swell from a storm, metres high, under a strong wind.</summary>
	Stormy,

	/// <summary>The swell and wind as the Ocean's own settings say.</summary>
	Custom,
}
